USE ROLE ACCOUNTADMIN;

-- 1. Create the role
CREATE ROLE IF NOT EXISTS PIPELINE_ROLE;

-- 2. Give the role only what it needs
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE PIPELINE_ROLE;
GRANT USAGE ON DATABASE SPINE_CT TO ROLE PIPELINE_ROLE;
GRANT USAGE, CREATE TABLE ON SCHEMA SPINE_CT.RAW TO ROLE PIPELINE_ROLE;

-- 3. Create the service user with key-pair login
CREATE USER IF NOT EXISTS PIPELINE_USER
  TYPE = SERVICE
  DEFAULT_ROLE = PIPELINE_ROLE
  DEFAULT_WAREHOUSE = COMPUTE_WH
  RSA_PUBLIC_KEY = '<your_public_key>';

-- 4. Give the role to the user
GRANT ROLE PIPELINE_ROLE TO USER PIPELINE_USER;

-- 5. Confirm
SHOW GRANTS TO ROLE PIPELINE_ROLE;
