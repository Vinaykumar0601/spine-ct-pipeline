USE ROLE SYSADMIN;
USE WAREHOUSE COMPUTE_WH;

SELECT 'Duplicate scan IDs' AS check_name,
       COUNT(*) - COUNT(DISTINCT SCAN_ID) AS issues
FROM SPINE_CT.RAW.SCAN_METADATA

UNION ALL
SELECT 'Missing required fields',
       COUNT_IF(SLICE_THICKNESS_MM IS NULL OR VERTEBRAE IS NULL
                OR LICENSE IS NULL OR S3_CT_PATH IS NULL OR CT_SHA256 IS NULL)
FROM SPINE_CT.RAW.SCAN_METADATA

UNION ALL
SELECT 'Mask missing or misaligned',
       COUNT_IF(MASK_FOUND = FALSE OR MASK_MATCHES_CT = FALSE)
FROM SPINE_CT.RAW.SCAN_METADATA

UNION ALL
SELECT 'Upload not verified',
       COUNT_IF(UPLOAD_VERIFIED = FALSE)
FROM SPINE_CT.RAW.SCAN_METADATA

UNION ALL
SELECT 'Slice thickness out of range',
       COUNT_IF(SLICE_THICKNESS_MM <= 0 OR SLICE_THICKNESS_MM > 5)
FROM SPINE_CT.RAW.SCAN_METADATA

UNION ALL
SELECT 'Fewer than 3 vertebrae labeled',
       COUNT_IF(NUM_VERTEBRAE < 3)
FROM SPINE_CT.RAW.SCAN_METADATA

UNION ALL
SELECT 'Patients with multiple scans',
       COUNT(*)
FROM (SELECT PATIENT_ID FROM SPINE_CT.RAW.SCAN_METADATA
      GROUP BY PATIENT_ID HAVING COUNT(*) > 1);
